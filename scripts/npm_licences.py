"""The licence record of the frontend's npm packages (issue #35).

Reads frontend/package-lock.json and writes docs/npm-licences.md: every
package with its version and licence, the app's own dependencies (what its
build can bundle) apart from the dev tools. A dependency of the app whose
licence isn't on GPL_COMPATIBLE fails the run, because the app is
GPL-3.0-or-later. scripts/check.sh runs this and fails if the record
differs from the last commit.

    python3 scripts/npm_licences.py
"""

from __future__ import annotations

import json
import pathlib
import sys
from typing import TypedDict

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOCK = ROOT / "frontend" / "package-lock.json"
OUT = ROOT / "docs" / "npm-licences.md"

# Licences a dependency of the GPL-3.0-or-later app may carry (SPDX ids).
GPL_COMPATIBLE = frozenset(
    {"MIT", "MIT-0", "ISC", "BSD-2-Clause", "BSD-3-Clause", "0BSD", "Apache-2.0", "MPL-2.0", "CC0-1.0", "BlueOak-1.0.0"}
)


class Package(TypedDict):
    name: str
    version: str
    licence: str
    dev: bool


def packages(lock: pathlib.Path = LOCK) -> list[Package]:
    """
    Every package in the lock file, once per name and version, with how it is used. A package installed at
    several paths counts as the app's if any copy is: npm's dev flag (set only on packages used just to build
    and test) decides, which is the cautious side. "devOptional" packages count as the app's.
    """
    data = json.loads(lock.read_text())
    found: dict[tuple[str, str], Package] = {}
    for path, entry in data["packages"].items():
        if not path:
            continue  # the frontend itself
        name = path.rsplit("node_modules/", 1)[-1]
        version = str(entry.get("version", "?"))
        dev = bool(entry.get("dev", False))
        seen = found.get((name, version))
        if seen is not None:
            seen["dev"] = seen["dev"] and dev
            continue
        found[(name, version)] = Package(
            name=name, version=version, licence=str(entry.get("license", "unknown")), dev=dev
        )
    return sorted(found.values(), key=lambda p: (p["name"], p["version"]))


def not_compatible(pkgs: list[Package]) -> list[Package]:
    """Dependencies of the app whose licence isn't on GPL_COMPATIBLE."""
    return [p for p in pkgs if not p["dev"] and p["licence"] not in GPL_COMPATIBLE]


def _table(pkgs: list[Package]) -> list[str]:
    rows = ["| Package | Version | Licence |", "|---|---|---|"]
    rows += [f"| `{p['name']}` | {p['version']} | {p['licence']} |" for p in pkgs]
    return rows


def render(pkgs: list[Package]) -> str:
    shipped = [p for p in pkgs if not p["dev"]]
    dev = [p for p in pkgs if p["dev"]]
    counts: dict[str, int] = {}
    for p in pkgs:
        counts[p["licence"]] = counts.get(p["licence"], 0) + 1
    lines = [
        "# npm packages and their licences",
        "",
        "Generated by `scripts/npm_licences.py` from `frontend/package-lock.json`;",
        "don't edit it by hand. `scripts/check.sh` fails if it is out of date, and",
        "if a dependency of the app has a licence that isn't compatible with",
        "GPL-3.0-or-later.",
        "",
        f"{len(pkgs)} packages (each name and version once): {len(shipped)} the app depends on, "
        f"{len(dev)} used only to build and test it.",
        "By licence: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))) + ".",
        "",
        "## Dependencies of the app",
        "",
        "Split by npm's dev flag: what the app's build can bundle, with their own dependencies and type definitions.",
        "",
        *_table(shipped),
        "",
        "## Used only to build and test it",
        "",
        *_table(dev),
        "",
    ]
    return "\n".join(lines)


def main(lock: pathlib.Path = LOCK, out: pathlib.Path = OUT) -> int:
    pkgs = packages(lock)
    bad = not_compatible(pkgs)
    if bad:
        for p in bad:
            print(
                f"{p['name']} {p['version']}: licence {p['licence']} is not on the GPL-compatible list", file=sys.stderr
            )
        return 1
    out.write_text(render(pkgs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
