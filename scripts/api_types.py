"""Writes frontend/src/types/api.ts from the backend's OpenAPI schema (#164; CLAUDE.md, "API").

The OpenAPI schema is the contract: the frontend's types are generated from it and committed, and
scripts/check.sh regenerates them and fails if they differ. Standard library only. An npm generator
(openapi-typescript) was considered, but its current release requires TypeScript 5 and the frontend
uses 6; the backend's schemas are plain Pydantic models, which this covers.

    python scripts/api_types.py            write frontend/src/types/api.ts
    python scripts/api_types.py --check    exit 1 if the file is not current
"""

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "types" / "api.ts"
HEADER = (
    "// Generated by scripts/api_types.py from the backend's OpenAPI schema. Do not edit:\n"
    "// change the backend's models and run `python scripts/api_types.py`.\n"
)


def schema() -> dict[str, Any]:
    """The backend's OpenAPI schema, made without starting a server."""
    sys.path.insert(0, str(ROOT / "backend"))
    from app.main import create_app  # noqa: PLC0415 (the backend is only importable once on the path)

    result: dict[str, Any] = create_app().openapi()
    return result


def ts_type(node: dict[str, Any]) -> str:
    """The TypeScript type for one JSON Schema node, as Pydantic writes them."""
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[1]
    if "anyOf" in node or "oneOf" in node:
        parts: list[str] = []
        for option in node.get("anyOf", node.get("oneOf", [])):
            text = ts_type(option)
            if text not in parts:
                parts.append(text)
        return " | ".join(parts)
    if "enum" in node:
        return " | ".join(json.dumps(value) for value in node["enum"])
    if "const" in node:
        return json.dumps(node["const"])
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**node, "type": k}) for k in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        item = ts_type(node.get("items", {}))
        return f"Array<{item}>"
    if kind == "object" or "properties" in node or "additionalProperties" in node:
        if "properties" in node:
            return (
                "{ "
                + " ".join(_member(n, p, n in node.get("required", [])) for n, p in node["properties"].items())
                + " }"
            )
        extra = node.get("additionalProperties")
        value = ts_type(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _key(name: str) -> str:
    return name if name.isidentifier() else json.dumps(name)


def _member(name: str, prop: dict[str, Any], required: bool) -> str:
    return f"{_key(name)}{'' if required else '?'}: {ts_type(prop)};"


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = text.replace("*/", "* /").strip().splitlines()
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {line}".rstrip() for line in lines), f"{indent} */"]


def _keys(node: Any) -> set[str]:
    """Every key used anywhere in a schema node: keywords, not words inside descriptions."""
    if isinstance(node, dict):
        found = set(node)
        for value in node.values():
            found |= _keys(value)
        return found
    if isinstance(node, list):
        return set().union(*(_keys(item) for item in node)) if node else set()
    return set()


def render(spec: dict[str, Any]) -> str:
    out = [HEADER]
    for name, node in sorted(spec["components"]["schemas"].items()):
        if not name.isidentifier():
            # e.g. FastAPI's Model-Input / Model-Output when a model differs between request and response
            raise ValueError(f"the schema {name!r} is not a TypeScript name; extend scripts/api_types.py for it")
        unsupported = {"allOf", "prefixItems", "not", "if"} & _keys(node)
        if unsupported:
            raise ValueError(
                f"the schema {name!r} uses {sorted(unsupported)}, which scripts/api_types.py doesn't cover"
            )
        out += _doc(node.get("description"), "")
        if node.get("type") == "object" and "properties" in node:
            out.append(f"export interface {name} {{")
            required = set(node.get("required", []))
            for prop_name, prop in node["properties"].items():
                out += _doc(prop.get("description"), "  ")
                out.append(f"  {_member(prop_name, prop, prop_name in required)}")
            out.append("}")
        else:
            out.append(f"export type {name} = {ts_type(node)};")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render(schema())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is not current: run `python scripts/api_types.py` and commit it.")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
